/// Consistent spacing rhythm for Dar Nasri screens.
abstract final class AppSpacing {
  static const xxs = 4.0;
  static const xs = 8.0;
  static const sm = 12.0;
  static const md = 16.0;
  static const lg = 24.0;
  static const xl = 32.0;

  /// Standard page inset used by catalog, details, branches, and shell pages.
  static const page = md;

  /// Bottom inset so content clears the floating assistant.
  static const pageBottom = 96.0;

  /// Gap between product grid columns and rows.
  static const gridGap = sm;
}
